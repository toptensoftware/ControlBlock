#!/usr/bin/env node
// node gen-types.js
// Writes firmware/main/config_types.gen.h: the C structs and op codes for the packed config,
// generated from the binpack schema (src/schema.js). The firmware reads the blob through them.
// test/types-header.test.js fails if the committed file is out of date.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { headerText } from "./src/pack.js";

export const TYPES_HEADER_PATH = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../firmware/main/config_types.gen.h");

const BANNER = "// Generated by tools/bake/gen-types.js from src/schema.js: do not edit, run `node gen-types.js`.\n";

// Normalised to LF so the file is the same whatever the platform
export const typesHeader = () => BANNER + headerText().replace(/\r\n/g, "\n");

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
{
    fs.writeFileSync(TYPES_HEADER_PATH, typesHeader());
    console.log(`${TYPES_HEADER_PATH}: written`);
}
