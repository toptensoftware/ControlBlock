#!/usr/bin/env node
// node gen-hid-keys.js
// Writes firmware/main/hid_keys.gen.h: the key and modifier names of src/hid.js as C tables, so the
// device's chord parser (hid_chord.cpp, for a script's hid.key) uses the bake's names and usage ids.
// test/hid-keys-header.test.js fails if the committed file is out of date.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { KEYS, MODIFIERS } from "./src/hid.js";

export const HID_KEYS_HEADER_PATH = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../firmware/main/hid_keys.gen.h");

const table = (name, map) =>
    `static const HidName ${name}[] = {\n` +
    Object.entries(map).map(([k, v]) => `    { ${JSON.stringify(k)}, 0x${v.toString(16).padStart(2, "0")} },\n`).join("") +
    "};\n";

export const hidKeysHeader = () =>
    "// Generated by tools/bake/gen-hid-keys.js from src/hid.js: do not edit, run `node gen-hid-keys.js`.\n" +
    "#pragma once\n#include <stdint.h>\n\n" +
    "struct HidName { const char *name; uint8_t value; };\n\n" +
    table("HID_MODIFIER_NAMES", MODIFIERS) + "\n" + table("HID_KEY_NAMES", KEYS);

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
{
    fs.writeFileSync(HID_KEYS_HEADER_PATH, hidKeysHeader());
    console.log(`${HID_KEYS_HEADER_PATH}: written`);
}
